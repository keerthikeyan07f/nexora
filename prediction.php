<script>
const targetSymbol = "<?php echo $symbol; ?>";
let predictionChart = null;

document.addEventListener('DOMContentLoaded', () => {
  executePrediction();
});

function executePrediction() {
  fetch(`api/stock_proxy.php?action=predict&symbol=${targetSymbol}`)
    .then(res => res.json())
    .then(data => {
      if (data.status === 'success') {
        document.getElementById('pCurPrice').innerText = formatPriceUSDINR(data.current_price);
        document.getElementById('pPredPrice').innerText = formatPriceUSDINR(data.predicted_price);
        
        const sign = data.change_pct >= 0 ? '+' : '';
        const pctEl = document.getElementById('pChangePct');
        pctEl.innerText = `${sign}${data.change_pct}%`;
        pctEl.className = data.change_pct >= 0 ? 'badge-bullish fs-8' : 'badge-bearish fs-8';

        document.getElementById('pTargetDate').innerText = data.target_date;
        document.getElementById('pSource').innerText = data.source === 'embedded_ml_engine' ? 'Python ML Engine' : 'Flask REST API';

        document.getElementById('mRMSE').innerText = data.metrics.rmse + ' USD';
        document.getElementById('mMAE').innerText = data.metrics.mae + ' USD';
        document.getElementById('mMAPE').innerText = data.metrics.mape + '%';
        document.getElementById('mArch').innerText = data.model_info.architecture;

        document.getElementById('pStatusBadge').innerHTML = '<i class="fas fa-check-circle me-1"></i> Inference Complete';

        // Populate hidden form inputs
        document.getElementById('formCurPrice').value = data.current_price;
        document.getElementById('formPredPrice').value = data.predicted_price;
        document.getElementById('formChangePct').value = data.change_pct;
        document.getElementById('formTargetDate').value = data.target_date;
        document.getElementById('formRMSE').value = data.metrics.rmse;
        document.getElementById('formMAE').value = data.metrics.mae;
        document.getElementById('formMAPE').value = data.metrics.mape;
        document.getElementById('formArch').value = data.model_info.architecture;
        document.getElementById('savePredBtn').disabled = false;

        // Fetch historical context to overlay prediction curve
        fetch(`api/stock_proxy.php?action=quote&symbol=${targetSymbol}&period=3m`)
          .then(res => res.json())
          .then(histData => {
            renderForecastChart(histData.history, data.forecast_dates, data.forecast_prices);
          });
      }
    });
}

function renderForecastChart(historicalSeries, forecastDates, forecastPrices) {
  const histDates = historicalSeries.map(h => h.date);
  const histPrices = historicalSeries.map(h => h.close);

  const combinedLabels = [...histDates, ...forecastDates];
  
  // Align forecast series data
  const histDataset = [...histPrices, ...Array(forecastPrices.length).fill(null)];
  const forecastDataset = [...Array(histPrices.length - 1).fill(null), histPrices[histPrices.length - 1], ...forecastPrices];

  const ctx = document.getElementById('predictionChartCanvas').getContext('2d');
  if (predictionChart) predictionChart.destroy();

  predictionChart = new Chart(ctx, {
    type: 'line',
    data: {
      labels: combinedLabels,
      datasets: [
        {
          label: 'Historical Close ($)',
          data: histDataset,
          borderColor: '#4facfe',
          borderWidth: 2,
          pointRadius: 0,
          tension: 0.2
        },
        {
          label: 'AI LSTM Forecast ($)',
          data: forecastDataset,
          borderColor: '#00e676',
          borderWidth: 3,
          borderDash: [5, 5],
          pointRadius: 4,
          pointBackgroundColor: '#00e676',
          tension: 0.2
        }
      ]
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: { legend: { labels: { color: '#8a99ad' } } },
      scales: {
        x: { grid: { display: false }, ticks: { color: '#8a99ad', maxTicksLimit: 12 } },
        y: { grid: { color: 'rgba(255, 255, 255, 0.05)' }, ticks: { color: '#8a99ad' } }
      }
    }
  });
}
